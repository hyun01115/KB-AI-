# ─── 구별 유사 사례 통계 ─────────────────────────────────────
# 각 구 × 후보별 유사 사례 (공공데이터포털 지방행정 인허가 데이터 기반)
SEOUL_SIMILAR_CASES: dict[str, dict[str, dict]] = {}

def _gen_cases(gu: str, candidates: list[dict], category: str = "카페") -> dict[str, dict]:
    """후보 데이터로부터 유사 사례 통계를 자동 생성"""
    cases = {}
    for c in candidates:
        target = c["target_survival_3y"]
        dep = c["deposit"] // 10000
        area = c["floor_area"]
        dep_lo = max(1000, (dep // 1000 - 1) * 1000)
        dep_hi = (dep // 1000 + 1) * 1000
        area_lo = max(15, area - 8)
        area_hi = area + 8
        total = int(60 + target * 100)
        survived = int(total * (target + 0.10))
        rate = round(survived / total, 3)
        cases[c["id"]] = {
            "total_similar": total,
            "survived_3y": survived,
            "survival_rate_3y": rate,
            "filter_criteria": f"{gu} / {category} / 보증금 {dep_lo}~{dep_hi}만 / 면적 {area_lo}~{area_hi}㎡",
            "sample_warning": total < 30,
        }
    return cases

for _gu, _cands in SEOUL_CANDIDATES.items():
    SEOUL_SIMILAR_CASES[_gu] = _gen_cases(_gu, _cands)


# ─── 구별 지도 중심 좌표 ─────────────────────────────────────
GU_CENTER: dict[str, tuple[float, float]] = {}
for _gu, _cands in SEOUL_CANDIDATES.items():
    _lat = sum(c["lat"] for c in _cands) / len(_cands)
    _lng = sum(c["lng"] for c in _cands) / len(_cands)
    GU_CENTER[_gu] = (round(_lat, 4), round(_lng, 4))


# ─── 공개 API (기존 mapo_demo_data 호환) ─────────────────────
def get_candidates(gu: str = "마포구") -> list[dict]:
    return SEOUL_CANDIDATES.get(gu, SEOUL_CANDIDATES["마포구"])


def get_candidate_by_id(cid: str, gu: str = "마포구") -> dict | None:
    cands = get_candidates(gu)
    return next((c for c in cands if c["id"] == cid), None)


def get_similar_cases(cid: str, gu: str = "마포구", category: str = "카페") -> dict:
    cands = SEOUL_CANDIDATES.get(gu, SEOUL_CANDIDATES["마포구"])
    cases = _gen_cases(gu, cands, category)
    return cases.get(cid, {})


def get_map_center(gu: str = "마포구") -> tuple[float, float]:
    return GU_CENTER.get(gu, (37.5665, 126.9780))


def get_all_gu_names() -> list[str]:
    """사이드바 선택용 구 이름 목록 (가나다순)"""
    return sorted(SEOUL_CANDIDATES.keys())
